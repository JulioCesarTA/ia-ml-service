"""Puertos de salida hacia los otros tres microservicios del comedor (HTTP en producción)."""
from typing import Protocol


class ServicioMenu(Protocol):
    """menu-inventario-service."""

    def menus_semana(self, turno: str, inicio: str | None = None) -> list[dict]: ...

    def menus_historial(self, desde: str, hasta: str) -> list[dict]: ...

    def apartar_porcion(self, menu_id: str, plato_id: str) -> None: ...

    def liberar_porcion(self, menu_id: str, plato_id: str) -> None: ...


class ServicioReservas(Protocol):
    """comensales-reservas-service."""

    def estudiantes(self) -> list[dict]: ...

    def beca(self, username: str) -> dict: ...

    def obtener_reserva(self, reserva_id: str) -> dict: ...

    def crear_reserva(self, datos: dict) -> str: ...

    def confirmar_reserva(self, reserva_id: str) -> tuple[bool, dict]: ...

    def cancelar_reserva(self, reserva_id: str) -> None: ...


class ServicioPagos(Protocol):
    """pagos-tickets-service."""

    def cobrar(self, datos: dict) -> dict: ...

    def verificar_pago(self, referencia: str) -> dict: ...

    def devolver_pago(self, pago_id: str) -> None: ...

    def recibo(self, referencia: str) -> dict: ...


class LectorDatosComedor(Protocol):
    """Lectura de solo-lectura de las colecciones que usan los reportes («menu», «comensales» o «pagos» + ruta)."""

    def direccion(self, servicio: str, ruta: str) -> str: ...

    def leer_json(self, direccion: str, espera: float = 20): ...
